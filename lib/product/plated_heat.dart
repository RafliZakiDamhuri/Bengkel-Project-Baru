            style: blackTextStyle.copyWith(
              fontSize: isWide ? 15 : 13,
              height: 1.8,
              fontWeight: FontWeight.w700,
              color: const Color(0xFF47515F),
            ),
          ),

          const SizedBox(height: 36),
          AppAssetImage(
            AppImages().platedProductSubproduct,
            width: contentWidth,
            height: isWide ? 420 : 230,
            fit: BoxFit.contain,
          ),
        ],
      ),
    );
  }

  Widget _buildKeyFeatures(
    double horizontal,
    double contentWidth,
    bool isWide,
  ) {
    final columns = contentWidth >= 900
        ? 3
        : contentWidth >= 560
        ? 2
        : 1;
    final cardWidth = columns == 1
        ? contentWidth
        : (contentWidth - (24 * (columns - 1))) / columns;

    final features = <ProductFeatureData>[
      const ProductFeatureData(
        title: 'Easy to Clean and Repair:',
        description:
            'PHE offers simple maintain to the end user, gasket units can be unbolted and dismantled to clean the plates manually, or cleaned using circulation pumps and chemical solutions.',
        label: 'Removable Tube Image',
      ),
      const ProductFeatureData(
        title: 'High Efficiency:',
        description:
            'The corrugated design forces the fluids into a turbulent flow, which breaks up thermal boundary layers and maximizes heat transfer rates. The design drives faster heat exchange.',
        label: 'On-Site Repair Image',
      ),
      const ProductFeatureData(
        title: 'Adaptable and Expandable:',
        description:
            'Because of their stacked, bolt-together structure, you can easily increase or decrease the heating or cooling capacity by adding or removing individual plates.',
        label: 'Warranty Badge Image',
      ),
    ];

    return Container(
      width: double.infinity,
      color: Colors.white,
      padding: EdgeInsets.symmetric(
        horizontal: horizontal,
        vertical: isWide ? 64 : 40,
      ),
      child: Column(
        children: [
          const ProductSectionHeading(text: 'KEY FEATURES & BENEFITS'),
          const SizedBox(height: 32),
          Wrap(
            spacing: 24,
            runSpacing: 24,
            children: features.asMap().entries.map((feature) {
              var stringImage = '';

              if (feature.key == 0) {
                stringImage = AppImages().platedKeyAndBenefits1;
              } else if (feature.key == 1) {
                stringImage = AppImages().platedKeyAndBenefits2;
              } else if (feature.key == 2) {
                stringImage = AppImages().platedKeyAndBenefits3;
              }
              return SizedBox(
                width: cardWidth,
                child: ProductFeatureCard(
                  title: feature.value.title,
                  description: feature.value.description,
                  label: feature.value.label,
                  imageHeight: isWide ? 350 : 190,
                  imageAssets:
                      stringImage, // Replace with actual image asset if available
                ),
              );
            }).toList(),
          ),
          const SizedBox(height: 48),
        ],
      ),
    );
  }

