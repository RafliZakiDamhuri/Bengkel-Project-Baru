    double horizontal,
    double contentWidth,
    bool isWide,
  ) {
    final columns = contentWidth >= 900
        ? 4
        : contentWidth >= 560
        ? 2
        : 1;
    final cardWidth = columns == 1
        ? contentWidth
        : (contentWidth - (20 * (columns - 1))) / columns;

    const applications = <String>[
      'HVAC SYSTEMS',
      'FOOD AND BEVERAGE INDUSTRY',
      'CHEMICAL AND PETROCHEMICAL',
      'POWER PLANTS OPERATIONS',
    ];

    return Container(
      width: double.infinity,
      color: const Color(0xFFF6F8FB),
      padding: EdgeInsets.symmetric(
        horizontal: horizontal,
        vertical: isWide ? 64 : 40,
      ),
      child: Column(
        children: [
          const ProductSectionHeading(text: 'APPLICATIONS'),
          const SizedBox(height: 24),
          Text(
            'The Indocool Plate Heat Exchanger (PHE) utilizes a stack of thin, corrugated metal plates to transfer heat efficiently between two fluids without letting them mix. Alternating channels force hot and cold fluids through the unit, where the corrugations create high turbulence that accelerates thermal conduction and convection while keeping the physical footprint significantly smaller than traditional shell-and-tube units.\n\nKey applications include HVAC systems for central heating and district energy, sanitary food and dairy processes like milk pasteurization, and chemical processing using corrosion-resistant alloys. Additionally, they serve pharmaceutical clean utilities as well as power plant cooling loops, turbine lube-oil cooling, and heavy industrial waste heat recovery.',
