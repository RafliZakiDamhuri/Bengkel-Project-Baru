  Widget _buildDescription(
    double horizontal,
    double contentWidth,
    bool isWide,
  ) {
    return Container(
      width: double.infinity,
      color: const Color(0xFFF6F8FB),
      padding: EdgeInsets.symmetric(
        horizontal: horizontal,
        vertical: isWide ? 64 : 40,
      ),
      child: Column(
        children: [
          const ProductSectionHeading(text: 'PRODUCT DESCRIPTION'),
          const SizedBox(height: 28),
          Text(
            'The Indocool Industrial Plate Heat Exchanger (PHE) is engineered to maximize fluid-to-fluid heat exchange with unmatched thermal precision and a compact footprint. Its matrix of corrugated plates generates high fluid turbulence to amplify heat transfer surface area through genuine counter-current flow. By reducing hold-up volume by 80% to 90% compared to traditional shell-and-tube units, it ensures precise temperature control.\n\nBeyond exceptional efficiency, the Indocool PHE enhances operational reliability by actively resisting fouling, stress, and corrosion. Its modular frame design allows effortless capacity expansion right on-site simply by adding or adjusting plates. This makes it a cost-effective, eco-friendly cooling solution across diverse sectors, including chemical processing, oil production, power generation, engine cooling, HVAC, and hygienic food processing.',
