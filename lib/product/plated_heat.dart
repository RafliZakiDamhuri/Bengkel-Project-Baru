                          'Plate heat exchangers are crafted to optimize heat transfer.  The corrugated plates substantially amplify the available surface area, facilitating the efficient transfer of heat from one fluid or gas to another. These units also boast a versatile design and are straightforward to maintain and service.',
                          style: blackTextStyle.copyWith(
                            fontSize: bodySize,
                            height: 1.55,
                            color: const Color(0xFF1F2933),
