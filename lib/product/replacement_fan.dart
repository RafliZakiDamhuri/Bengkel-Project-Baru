              fontSize: isWide ? 15 : 13,
              height: 1.8,
              fontWeight: FontWeight.w700,
              color: const Color(0xFF47515F),
            ),
          ),

          const SizedBox(height: 36),
          AppAssetImage(
            AppImages().replacementFanSubproduct,
            width: contentWidth,
            height: isWide ? 420 : 230,
            fit: BoxFit.contain,
          ),
        ],
      ),
    );
  }

  Widget _buildKeyFeatures(
    double horizontal,
    double contentWidth,
    bool isWide,
  ) {
    final columns = contentWidth >= 900
        ? 3
        : contentWidth >= 560
        ? 2
        : 1;
    final cardWidth = columns == 1
        ? contentWidth
        : (contentWidth - (24 * (columns - 1))) / columns;

    final features = <ProductFeatureData>[
      const ProductFeatureData(
        title: 'Customizable & Modular Efficiency:',
        description:
            'Features configurable blade profiles, variable pitch angles, and adaptable hub types to deliver target static pressure and airflow without needing to replace existing motors or casings.',
        label: 'Removable Tube Image',
      ),
      const ProductFeatureData(
        title: 'Harsh-Environment Resistance:',
        description:
            'Constructed from specialized composite polymers and high-grade aluminum alloys, offering anti-static, flame-resistant, corrosion-resistant, and high-temperature capabilities.',
        label: 'On-Site Repair Image',
      ),
      const ProductFeatureData(
        title: 'Lower Operational Costs:',
        description:
            'Reduces dust clogging, minimizes noise, and provides precise aerodynamic tuning via winglets and intelligent drives, preventing engine overheating and maintenance expenses.',
        label: 'Warranty Badge Image',
      ),
    ];

    return Container(
      width: double.infinity,
      color: Colors.white,
      padding: EdgeInsets.symmetric(
        horizontal: horizontal,
        vertical: isWide ? 64 : 40,
      ),
      child: Column(
        children: [
          const ProductSectionHeading(text: 'KEY FEATURES & BENEFITS'),
          const SizedBox(height: 32),
          Wrap(
            spacing: 24,
            runSpacing: 24,
            children: features.asMap().entries.map((feature) {
              var stringImage = '';

              if (feature.key == 0) {
                stringImage = AppImages().replacementFanKeyAndBenefits1;
              } else if (feature.key == 1) {
                stringImage = AppImages().replacementFanKeyAndBenefits2;
              } else if (feature.key == 2) {
                stringImage = AppImages().replacementFanKeyAndBenefits3;
              }
              return SizedBox(
                width: cardWidth,
                child: ProductFeatureCard(
                  title: feature.value.title,
                  description: feature.value.description,
                  label: feature.value.label,
                  imageHeight: isWide ? 350 : 190,
                  imageAssets:
                      stringImage, // Replace with actual image asset if available
                ),
              );
            }).toList(),
          ),
          const SizedBox(height: 48),
        ],
      ),
    );
  }

