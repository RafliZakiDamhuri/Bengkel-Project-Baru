          const SizedBox(height: 28),
          Text(
            'The Indocool Heavy-Duty Modular Axial Fan System is engineered to deliver high-performance airflow management under extreme environmental conditions, including heavy dust, severe vibration, high temperatures, and high static pressure. Built with fully configurable blade profiles, variable pitch angles, and durable hub configurations, these impellers optimize static pressure and thermal dissipation without requiring motor or casing modifications.\n\nEngineered using advanced composite polymers—such as glass-reinforced polyamide (PAG/PPG), anti-static carbon-fiber reinforced materials (PAGAS/PAG6-C), low-flammability synthetics (PAGV1), and high-grade aluminum alloys (AL 400C)—the fan range ensures exceptional corrosion resistance, explosion-proof compliance, and reliable operation across extreme thermal and smoke-extraction applications.',
