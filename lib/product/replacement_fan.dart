        : (contentWidth - (20 * (columns - 1))) / columns;

    const applications = <String>[
      'MINING & OFF-HIGHWAY FLEET',
      'CRUSHING & PROCESSING PLANT',
      'POWER GENERATION',
      'INDUSTRIAL INFRASTRUCTURE',
    ];

    return Container(
      width: double.infinity,
      color: const Color(0xFFF6F8FB),
      padding: EdgeInsets.symmetric(
        horizontal: horizontal,
        vertical: isWide ? 64 : 40,
      ),
      child: Column(
        children: [
          const ProductSectionHeading(text: 'APPLICATIONS'),
          const SizedBox(height: 24),
          Text(
            'Designed for versatile deployment, this industrial cooling line encompasses modular adjustable impellers, high-pressure one-piece molded fans, and complete integrated axial assemblies equipped with AC, EC, or intelligent DC electric drives. Complementary accessories, including viscous clutches, winglet extensions, and custom hubs—allow precise aerodynamic tuning to prevent clogging, reduce noise, and maximize energy efficiency.\n\nThe system provides essential thermal regulation and ventilation across heavy-duty sectors, including off-highway mining vehicles (excavators, dump trucks, wheel loaders), processing plant machinery (crushers, screeners, power generators), and large-scale industrial ventilation systems.',
            textAlign: isWide ? TextAlign.center : TextAlign.left,
            style: blackTextStyle.copyWith(
              fontWeight: FontWeight.w900,
              fontSize: isWide ? 15 : 13,
